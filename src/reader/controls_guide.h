#ifndef CONTROLS_GUIDE_H_
#define CONTROLS_GUIDE_H_

inline const char *controls_guide_text()
{
    return
        "Up and down scroll this guide. Any other button closes it.\n"
        "\n"
        "Reading\n"
        "Scroll mode: up and down move one line. Hold to keep going.\n"
        "Scroll mode: left and right move one screen.\n"
        "Page mode: the D-pad and the shoulder buttons turn a whole page. Line scrolling is off.\n"
        "L1 and R1 match left and right. Settings can move that to L2 and R2.\n"
        "A shows or hides the progress line.\n"
        "B closes the book.\n"
        "X opens settings.\n"
        "Y selects a word near the middle of the page. A bar names the buttons.\n"
        "Select opens the book menu. Chapters lists the chapters, with the one you are reading marked; Y there finds a chapter by letters.\n"
        "After you pick a search result, the words stay marked and the chapter shoulder pair steps between matches. Clear search in the book menu ends it.\n"
        "Next mark and Previous mark go to the next or previous bookmark or highlight.\n"
        "Book map shows the whole book as a bar with chapters, bookmarks and highlights. Left and right move, up and down change chapter, A goes.\n"
        "View picture opens a picture full screen. A zooms, Y fits, the D-pad moves around, B closes.\n"
        "Add bookmark saves the place. Bookmarks lists them: A goes there, X deletes one.\n"
        "Go to % picks a place by percent: left and right move 1, up and down move 10, A goes.\n"
        "In Page mode, once the pages are counted, Go to page picks a page the same way. Go to book page types a printed page number, for a book that lists its pages.\n"
        "Skim the book shows a grid of tiles over the book: D-pad moves, L and R go a screen, A goes there.\n"
        "Look up in... on a word lets you pick another dictionary, or all of them. In an entry, A picks a word and A again looks it up.\n"
        "Look up a word opens the keyboard and shows the entry for the word you type; Browse the dictionary lists words by their first letters.\n"
        "The shoulder pair that does not turn pages jumps to the previous or next chapter.\n"
        "Jump back returns to where you were before the last jump.\n"
        "Reading history is a calendar of the time read each day. Reading stats shows the time you have read. Word list keeps every word you looked up: A shows it, X deletes it.\n"
        "Highlights lists what you marked, in book order: A goes there, X removes one.\n"
        "Export highlights writes them to a text file next to the book.\n"
        "Start opens this guide.\n"
        "Menu quits. A Menu chord does not.\n"
        "\n"
        "Selecting\n"
        "The cursor starts near the middle of the page. Commas, periods, and quotes stay outside that word.\n"
        "D-pad moves the cursor. Hold to repeat. Left or right at the edge of the page turns the page.\n"
        "Start keeps the first word and adds the words you move through. X grows the selection to the sentence, then the paragraph, then back to the word.\n"
        "A opens Look up, Search book, Highlight, Underline and Strike out. Look up and Search use the word at the cursor, in the language of the book. The marks cover every selected word.\n"
        "On a link, such as a footnote number, A also offers Show note, which reads the note, and Go to link.\n"
        "B or Y leaves selection.\n"
        "\n"
        "Progress\n"
        "Scroll mode shows the percent. That number follows the text.\n"
        "Page mode shows the page and how many pages. Turning a page adds 1.\n"
        "A new chapter, a title page, and a picture that does not fit start at the top of a page.\n"
        "Choosing Page counts from the start, then jumps to the top of the page you were on.\n"
        "While the pages are counted, a Counting pages screen shows the progress and nothing else. B still leaves the book.\n"
        "Book or Chapter chooses the whole book or the current chapter, for both modes.\n"
        "In Chapter mode, turning past the end of a chapter moves into the next one.\n"
        "\n"
        "Settings\n"
        "The name is on the left and the choice is on the right. The book stays behind the menu.\n"
        "Up and down change the row. Left and right change the choice.\n"
        "Reading switches Scroll and Page.\n"
        "Bar left, middle and right choose what the line under the text shows: titles, page, chapter or book percent, time, date.\n"
        "Time left in the chapter or book comes from how fast you have been turning pages. Battery shows the charge.\n"
        "Clock switches the time between 24-hour and 12-hour.\n"
        "The four margins, Line spacing, Justify, Indent, Paragraph gap, Bold text and Hyphenate change the shape of the text. Justify spreads each line to both edges. Hyphenate splits long words at the end of a line.\n"
        "Word spacing, Letter spacing and Scroll overlap tune the text. Screen turns the page to portrait and restarts the reader when settings close. Style tweaks, Layout profiles, Custom colors and Typography open their own lists. Pictures can invert, add contrast to, or hide pictures. Thin bar draws a progress line with chapter ticks along the bottom.\n"
        "Reading ruler marks one line (Line) or fades the others (Focus) and moves with up and down. Dictionary picks the one for lookups. Screen dim darkens the picture. Book styles turns off the epub stylesheet for the next book. Highlight color picks the color of new highlights.\n"
        "Cover screen shows the cover of the open epub after the time you pick with no button pressed.\n"
        "Night theme switches to a theme between two hours of the day and back.\n"
        "Inside a book these belong to that book alone. In the book list they set the defaults.\n"
        "Auto exit saves and quits after the time you pick with no button pressed.\n"
        "Controls, then A, opens this guide.\n"
        "B closes settings.\n"
        "\n"
        "Book list\n"
        "Each book shows its title and author, read from the book, then its type and size. Folders are marked Folder.\n"
        "Up and down move one row. Left and right move half a screen.\n"
        "A opens the book or folder. X opens settings.\n"
        "Each folder remembers its own order, list or grid and hide-finished. Library tools also has All highlights, Search inside all books, Browse by tag and Tidy this folder. In the list the shoulder pair that does not page jumps to the next or previous first letter. Y, Show lists only books not opened, in progress, favorites or finished. Start cycles name, title, author, series, recent, size, newest and most read.\n"
        "Y opens options for the selected entry: mark books to copy, move or delete, new folder, paste here, properties, favorite, status, hide finished books, recent books, search the library, collections, library tools (books by status, copies, unopened books, backup and restore, books over wifi), rename and delete.\n"
        "Select switches between the list and the cover grid.\n"
        "Start changes the order: name, title, author, series, or recently read.\n"
        "A book you have opened shows how far you got, as a percent or Done, and as a bar on its cover.\n"
        "Continue: at the top of a folder opens the book you read last. A row that starts with * is a favorite.\n"
        "In the grid, D-pad moves one cover. L1 and R1 move a screen.\n"
        "A long name slides when it is selected.\n"
        "B goes up one folder. Menu quits.\n";
}

#endif
